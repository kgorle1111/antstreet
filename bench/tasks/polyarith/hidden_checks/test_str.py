from fractions import Fraction

import pytest
from polyarith import poly_str


@pytest.mark.parametrize(
    ("p", "text"),
    [
        ([1, 2, 3], "3x^2 + 2x + 1"),
        ([1, -1], "-x + 1"),
        ([0, 0, 1], "x^2"),
        ([Fraction(-3, 2), 4], "4x - (3/2)"),
        ([0, Fraction(-1, 3)], "-(1/3)x"),
        ([-5], "-5"),
        ([], "0"),
        ([0, 0], "0"),
        ([1], "1"),
        ([-1], "-1"),
        ([0, 1], "x"),
        ([0, -1], "-x"),
        ([2, 0, -1], "-x^2 + 2"),
        ([0, 0, 0, 5], "5x^3"),
        ([1, 1, 1], "x^2 + x + 1"),
        ([-1, -1, -1], "-x^2 - x - 1"),
        ([Fraction(1, 2), Fraction(1, 2)], "(1/2)x + (1/2)"),
        ([Fraction(-1, 2), 0, 3], "3x^2 - (1/2)"),
        ([Fraction(4, 2), 1], "x + 2"),
        ([Fraction(2, 4)], "(1/2)"),
        ([Fraction(3, 2)], "(3/2)"),
        ([Fraction(-3, 2)], "-(3/2)"),
        ([1, 0, 0], "1"),
        ([3, -7, 0, 0, 1], "x^4 - 7x + 3"),
        ([0, 12], "12x"),
        ([-3, 10**20], "100000000000000000000x - 3"),
        ([0, 0, -2, 1], "x^3 - 2x^2"),
        ([0, 0, 0, 0, 0, -1], "-x^5"),
        ([Fraction(1, 3), 0, Fraction(-5, 7)], "-(5/7)x^2 + (1/3)"),
    ],
)
def test_text(p, text):
    assert poly_str(p) == text
